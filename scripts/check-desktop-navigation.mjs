import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8');
assert(existsSync(new URL('../src/styles/desktop-navigation.css', import.meta.url)), 'Desktop horizontal navigation stylesheet missing');
const css = read('src/styles/desktop-navigation.css');
assert.match(css, /@media \(min-width: 1024px\)/);
for (const selector of ['desktop-navigation', 'desktop-main', 'account-side-nav', 'legal-nav', 'admin-navigation']) assert(css.includes(selector), selector);
for (const p of ['src/routes/index.tsx','src/components/movie-detail/DetailSidebar.tsx','src/components/player/PlayerSidebar.tsx']) assert(read(p).includes('desktop-navigation'), p);
assert.match(read('src/routes/__root.tsx'), /desktop-navigation.css/);
assert.match(css, /flex-direction: row/);
assert.match(css, /margin-left: 0/);
assert.match(css, /overflow: visible/);
assert.match(css, /#genre-dropdown-menu/);
assert.match(css, /#country-dropdown-menu/);
assert.match(css, /radial-gradient\(circle at 10% 30%/);
assert.match(css, /border-radius: 18px 18px 0 0/);
assert.match(css, /\.details-root \.topbar/);
assert.match(css, /\.player-page-root \.topbar/);
assert.match(css, /\.desktop-source-nav\s*\{\s*display:\s*none/);
const home = read('src/routes/index.tsx');
assert.match(home, /className="desktop-source-nav [^"]+"/);
assert.match(home, /navigate\(\{ to: "\/settings" \}\)/);
assert.match(home, /<span>Cài đặt<\/span>/);
assert.match(css, /prefers-reduced-motion/);
console.log('Desktop navbar contract passed: reference styling, existing behavior, responsive mobile boundary');
