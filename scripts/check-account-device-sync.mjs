import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8");
const history = read("convex/watchHistory.ts");
const favorites = read("convex/favorites.ts");
const watch = read("src/routes/watch.$slug.tsx");
const detail = read("src/routes/movie.$slug.tsx");
const home = read("src/routes/index.tsx");
const account = read("src/routes/account.tsx");
assert.match(history, /export const get = query/);
assert.match(favorites, /export const set = mutation/);
assert.match(watch, /api\.watchHistory\.save/);
assert.match(watch, /api\.watchHistory\.get/);
assert.match(watch, /api\.favorites\.(set|remove)/);
assert.match(detail, /api\.favorites\.(set|remove)/);
assert.match(home, /api\.favorites\.list/);
assert.match(home, /api\.favorites\.set/);
assert.match(account, /api\.favorites\.list/);
const auth = read("src/lib/auth-data-provider.tsx");
const controls = read("src/components/player/PlayerControls.tsx");
assert.match(auth, /preferences/);
assert.match(auth, /savePreference/);
assert.match(controls, /savePreference/);
assert.doesNotMatch(account, /Bộ sưu tập đã lưu trên trình duyệt này/);
console.log("Account sync passed: cloud favorites/history producers and consumers across routes");
